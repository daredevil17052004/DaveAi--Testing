"""API tests for Reqres endpoints (assignment filename: api_tests.py)."""

from datetime import datetime
import os

import pytest
import requests

from tests.conftest import check_rate_limit

HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
    ),
    "Content-Type": "application/json",
}

# Include API key header when REQRES_API_KEY is set in the environment.
# A key raises the per-day quota above the anonymous 40-request limit.
if os.environ.get("REQRES_API_KEY"):
    HEADERS["x-api-key"] = os.environ.get("REQRES_API_KEY")


@pytest.mark.api
def test_get_users_list_success(api_base_url):
    """Verify that paginated users endpoint returns 200 with expected schema."""
    response = requests.get(f"{api_base_url}/api/users?page=2", headers=HEADERS, timeout=10)
    check_rate_limit(response)

    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"

    data = response.json()
    assert data["page"] == 2, f"Expected page 2, got {data.get('page')}"
    assert data["per_page"] == 6, f"Expected 6 users per page, got {data.get('per_page')}"
    assert data["total"] >= 12, "Total user count should be at least 12"
    assert isinstance(data["data"], list), "'data' field must be a list"
    assert len(data["data"]) > 0, "Users list should not be empty"

    required_keys = {"id", "email", "first_name", "last_name", "avatar"}
    for user in data["data"]:
        assert required_keys.issubset(user.keys()), f"Missing fields in user record: {user}"
        assert "@" in user["email"], f"Invalid email format: {user['email']}"
        assert user["avatar"].startswith("http"), f"Avatar should be a valid URL: {user['avatar']}"


@pytest.mark.api
def test_get_users_list_latency_sla(api_base_url):
    """Verify that the users endpoint responds within the 2.5s SLA."""
    response = requests.get(f"{api_base_url}/api/users?page=2", headers=HEADERS, timeout=10)
    check_rate_limit(response)

    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"
    assert response.elapsed.total_seconds() < 2.5, "Response latency exceeded 2.5s SLA"


@pytest.mark.api
def test_get_single_user_content_and_structure(api_base_url):
    """Verify single user endpoint response structure and data accuracy."""
    user_id = 2
    response = requests.get(f"{api_base_url}/api/users/{user_id}", headers=HEADERS, timeout=10)
    check_rate_limit(response)

    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"

    body = response.json()
    assert "data" in body, "Response body must contain 'data' object"
    user = body["data"]

    assert user["id"] == user_id, f"Expected user id {user_id}, got {user['id']}"
    assert user["first_name"] == "Janet", f"Expected first name 'Janet', got {user['first_name']}"
    assert user["last_name"] == "Weaver", f"Expected last name 'Weaver', got {user['last_name']}"
    assert user["email"] == "janet.weaver@reqres.in", f"Unexpected email: {user['email']}"

    assert "support" in body, "Response body must contain 'support' section"
    assert "url" in body["support"], "'support' must contain 'url'"
    assert "text" in body["support"], "'support' must contain 'text'"


@pytest.mark.api
def test_create_user_success(api_base_url):
    """Verify user creation returns 201 with generated id and a valid ISO 8601 timestamp."""
    payload = {"name": "morpheus", "job": "leader"}
    response = requests.post(f"{api_base_url}/api/users", json=payload, headers=HEADERS, timeout=10)
    check_rate_limit(response)

    assert response.status_code == 201, f"Expected 201 Created, got {response.status_code}"

    body = response.json()
    assert body["name"] == payload["name"], f"Expected name {payload['name']}, got {body.get('name')}"
    assert body["job"] == payload["job"], f"Expected job {payload['job']}, got {body.get('job')}"
    assert "id" in body and body["id"] != "", "Expected non-empty 'id' generated by server"

    assert "createdAt" in body, "Expected 'createdAt' field in response"
    # Reqres returns timestamps with a trailing 'Z'. datetime.fromisoformat (Python 3.11+)
    # handles 'Z' natively, but replacing it with '+00:00' works on 3.10 and 3.11+ alike.
    iso_string = body["createdAt"].replace("Z", "+00:00")
    created_at = datetime.fromisoformat(iso_string)
    assert created_at.year >= 2024, f"Unexpected creation year: {created_at.year}"


@pytest.mark.api
def test_register_missing_password_error(api_base_url):
    """Verify user registration without a password returns 400 Bad Request."""
    invalid_payload = {"email": "sydney@fife"}
    response = requests.post(
        f"{api_base_url}/api/register",
        json=invalid_payload,
        headers=HEADERS,
        timeout=10,
    )
    check_rate_limit(response)

    assert response.status_code == 400, f"Expected 400 Bad Request, got {response.status_code}"

    body = response.json()
    assert "error" in body, "Response must contain 'error' key for invalid request"
    assert body["error"] == "Missing password", (
        f"Expected 'Missing password' error, got '{body['error']}'"
    )


@pytest.mark.api
def test_get_non_existent_user_not_found(api_base_url):
    """Verify requesting a non-existent user returns 404 and an empty body."""
