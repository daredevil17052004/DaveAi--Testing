"""
API Automated Test Suite for Reqres (https://reqres.in)
Covers happy paths, content assertions, schema validation, and error scenarios.
"""

import os
import pytest
import requests

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
    "Content-Type": "application/json",
}

# Attach API key if supplied via environment variable
if os.environ.get("REQRES_API_KEY"):
    HEADERS["x-api-key"] = os.environ.get("REQRES_API_KEY")


@pytest.mark.api
def test_get_users_list_success(api_base_url):
    """
    Test Case 1: Validate Successful User List Retrieval (HTTP 200)
    - Verifies HTTP 200 status code
    - Asserts pagination keys (page, per_page, total, total_pages)
    - Validates data list is populated and user objects have required fields
    - Asserts response latency is within acceptable SLA (< 2.5s)
    """
    url = f"{api_base_url}/api/users?page=2"
    response = requests.get(url, headers=HEADERS, timeout=10)

    # 1. Status Code Validation
    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"

    # 2. Performance / Latency SLA Check
    assert response.elapsed.total_seconds() < 2.5, "Response latency exceeded 2.5 seconds SLA"

    data = response.json()

    # 3. Pagination Structure Assertions
    assert data["page"] == 2, f"Expected page 2, got {data.get('page')}"
    assert data["per_page"] == 6, f"Expected 6 users per page, got {data.get('per_page')}"
    assert data["total"] >= 12, "Total user count should be at least 12"
    assert isinstance(data["data"], list), "'data' field must be a list"
    assert len(data["data"]) > 0, "Users list should not be empty"

    # 4. Content and Schema Validation for Each Item
    required_keys = {"id", "email", "first_name", "last_name", "avatar"}
    for user in data["data"]:
        assert required_keys.issubset(user.keys()), f"Missing fields in user record: {user}"
        assert "@" in user["email"], f"Invalid email format: {user['email']}"
        assert user["avatar"].startswith("http"), f"Avatar should be a valid URL: {user['avatar']}"


@pytest.mark.api
def test_get_single_user_content_and_structure(api_base_url):
    """
    Test Case 2: Validate Specific User Content & Support Block (HTTP 200)
    - Validates retrieval of specific user (ID: 2)
    - Confirms exact values of user properties (first_name, last_name, email)
    - Validates nested 'support' metadata section
    """
    user_id = 2
    url = f"{api_base_url}/api/users/{user_id}"
    response = requests.get(url, headers=HEADERS, timeout=10)

    # Status Code Check
    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"

    body = response.json()
    assert "data" in body, "Response body must contain 'data' object"
    user = body["data"]

    # Content Assertions
    assert user["id"] == user_id, f"Expected user id {user_id}, got {user['id']}"
    assert user["first_name"] == "Janet", f"Expected first name 'Janet', got {user['first_name']}"
    assert user["last_name"] == "Weaver", f"Expected last name 'Weaver', got {user['last_name']}"
    assert user["email"] == "janet.weaver@reqres.in", f"Unexpected email: {user['email']}"

    # Nested Support Block Verification
    assert "support" in body, "Response body must contain 'support' section"
    assert "url" in body["support"], "'support' must contain 'url'"
    assert "text" in body["support"], "'support' must contain 'text'"


@pytest.mark.api
def test_create_user_success(api_base_url):
    """
    Test Case 3: Validate Resource Creation (HTTP 201 Created)
    - Sends POST request with valid user payload
    - Confirms HTTP 201 Created status
    - Validates server echoes posted data (name, job)
    - Validates system generates unique ID and ISO createdAt timestamp
    """
    url = f"{api_base_url}/api/users"
    payload = {"name": "morpheus", "job": "leader"}

    response = requests.post(url, json=payload, headers=HEADERS, timeout=10)

    # Status Code Check
    assert response.status_code == 201, f"Expected 201 Created, got {response.status_code}"

    body = response.json()

    # Content & Echo Assertions
    assert body["name"] == payload["name"], f"Expected name {payload['name']}, got {body.get('name')}"
    assert body["job"] == payload["job"], f"Expected job {payload['job']}, got {body.get('job')}"

    # System-generated Fields Assertion
    assert "id" in body and body["id"] != "", "Expected non-empty 'id' generated by server"
    assert "createdAt" in body and len(body["createdAt"]) > 10, "Expected valid 'createdAt' timestamp"


@pytest.mark.api
def test_register_missing_password_error(api_base_url):
    """
    Test Case 4: Validate Error Handling - Missing Parameter (HTTP 400 Bad Request)
    - Tests negative scenario: Attempting user registration without password
    - Verifies HTTP 400 Bad Request status code
    - Validates specific error message in response body
    """
    url = f"{api_base_url}/api/register"
    invalid_payload = {"email": "sydney@fife"}  # Missing password

    response = requests.post(url, json=invalid_payload, headers=HEADERS, timeout=10)

    # Status Code Check
    assert response.status_code == 400, f"Expected 400 Bad Request, got {response.status_code}"

    body = response.json()
    assert "error" in body, "Response must contain 'error' key for invalid request"
    assert body["error"] == "Missing password", f"Expected 'Missing password' error, got '{body['error']}'"


@pytest.mark.api
def test_get_non_existent_user_not_found(api_base_url):
    """
    Test Case 5: Validate Error Handling - Resource Not Found (HTTP 404)
    - Queries a user ID known not to exist (ID: 999)
    - Verifies HTTP 404 Not Found response
    - Asserts response body is empty dictionary
    """
